//! PV Studio desktop shell. Only this crate depends on Tauri; business logic lives in
//! `crates/pv-model`, `crates/pv-store` and `crates/pv-pipeline` (statics compute thread).

mod bench;
mod commands;
mod compute;
mod export;
mod roof;
mod state;

use std::sync::Arc;

use specta_typescript::{semantic, Typescript};
use tauri::Manager;
use tauri_specta::{collect_commands, collect_events, Builder};

use crate::state::AppState;

/// Where the generated TypeScript bindings are written (never edit that file by hand).
pub const BINDINGS_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../apps/desktop/src/bindings/index.ts"
);

/// Registry of every command and event exposed to the front-end.
///
/// Floats are exported as `number` (not `number | null`): Rust never emits non-finite
/// values, commands reject them, and a `NaN` sent from JS fails deserialisation at the IPC
/// boundary instead of reaching the model.
#[must_use]
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::stress_project_path,
            commands::create_stress_project,
            commands::open_project,
            commands::new_project,
            commands::open_project_dialog,
            commands::get_project_summary,
            commands::plan_roof,
            roof::preview_roof,
            roof::roof_preset,
            roof::roof_form,
            roof::roof_from_form,
            commands::get_module_buffer,
            commands::get_module_buffer_for,
            commands::apply_command,
            commands::undo,
            commands::redo,
            compute::get_statics_snapshot,
            compute::get_bom,
            compute::freeze_bom,
            compute::list_bom_snapshots,
            compute::get_bom_snapshot,
            export::save_export,
            bench::platform_info,
            bench::write_bench_report,
        ])
        .events(collect_events![
            commands::ModelChanged,
            compute::ResultReady,
            compute::ComputeState,
            compute::ComputeFailed,
        ])
        .semantic_types(semantic::Configuration::empty().enable_lossless_floats())
}

/// Writes the TypeScript bindings to [`BINDINGS_PATH`].
///
/// # Errors
/// When the exporter fails (e.g. an unsupported type) or the file cannot be written.
pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), specta_typescript::Error> {
    builder.export(
        Typescript::default()
            .header("// GENERATED by tauri-specta from src-tauri — do not edit. Regenerate with `pnpm bindings`.\n"),
        BINDINGS_PATH,
    )
}

/// Builds and runs the Tauri application.
pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder).expect("failed to export TypeScript bindings");

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .manage(AppState::default())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            // The statics compute thread (pv-pipeline), owner of the dependency graph.
            let state = app.state::<AppState>();
            let handle = compute::start(app.handle(), Arc::clone(&state.results))?;
            state.attach_compute(handle);
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("failed to run the PV Studio application");
}
